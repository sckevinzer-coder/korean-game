String _lookup(AppLocale locale, String key) {
  switch (locale) {
    case AppLocale.korean:
      return _ko[key] ?? _ja[key] ?? key;
    case AppLocale.english:
      return _en[key] ?? _ja[key] ?? key;
    case AppLocale.japanese:
      return _ja[key] ?? key;
  }
}

/// Translates [key] into [locale], falling back to Japanese.
String tr(AppLocale locale, String key) => _lookup(locale, key);

/// Translates [key] and substitutes `{name}` placeholders with [params].
String trParams(AppLocale locale, String key, Map<String, Object> params) {
  var text = _lookup(locale, key);
  for (final entry in params.entries) {
    text = text.replaceAll('{${entry.key}}', '${entry.value}');
  }
  return text;
}
